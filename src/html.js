/**
 * Self-contained HTML gallery: inline SVG + stats tables, no external assets.
 */

import { escapeXml } from "./svg.js";

function pct(part, whole) {
  if (!whole) return "0.0%";
  return ((part / whole) * 100).toFixed(1) + "%";
}

export function renderHtml({ svg, title, graph, stats, sourceName }) {
  const { nodes, layers } = graph;
  const links = [...nodes.values()].flatMap((n) => n.outs);
  const top = [...links]
    .sort((a, b) => b.value - a.value || a.source.localeCompare(b.source))
    .slice(0, 15);

  const linkRows = top
    .map(
      (l) =>
        `<tr><td>${escapeXml(l.source)}</td><td>${escapeXml(l.target)}</td>` +
        `<td class="num">${l.value}</td><td class="num">${pct(l.value, stats.totalValue)}</td></tr>`
    )
    .join("");

  const nodeRows = layers
    .flatMap((names, layer) =>
      names.map((name) => {
        const n = nodes.get(name);
        return (
          `<tr><td class="num">${layer}</td><td>${escapeXml(name)}</td>` +
          `<td class="num">${n.value}</td><td class="num">${n.ins.length}</td>` +
          `<td class="num">${n.outs.length}</td></tr>`
        );
      })
    )
    .join("");

  const esc = escapeXml;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)} — flowdeck</title>
<style>
  :root { color-scheme: light; }
  body { font-family: system-ui, sans-serif; margin: 2rem auto; max-width: 68rem;
         padding: 0 1rem; color: #1c1c1c; }
  h1 { font-size: 1.4rem; margin-bottom: 0.2rem; }
  p.meta { color: #666; margin-top: 0; }
  figure { margin: 1.5rem 0; overflow-x: auto; border: 1px solid #e3e3e3;
           border-radius: 8px; padding: 0.5rem; background: #fff; }
  table { border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: 0.92rem; }
  caption { text-align: left; font-weight: 600; padding: 0.4rem 0; }
  th, td { border-bottom: 1px solid #e5e5e5; padding: 0.35rem 0.55rem; text-align: left; }
  th { background: #f6f6f6; }
  td.num, th.num { text-align: right; font-variant-numeric: tabular-nums; }
</style>
</head>
<body>
<h1>${esc(title)}</h1>
<p class="meta">Generated by flowdeck from <code>${esc(sourceName)}</code> —
${stats.nodeCount} nodes · ${stats.linkCount} flows · ${stats.layerCount} layers ·
total ${stats.totalValue}</p>
<figure>${svg}</figure>
<table>
<caption>Top flows</caption>
<thead><tr><th>Source</th><th>Target</th><th class="num">Value</th><th class="num">Share</th></tr></thead>
<tbody>${linkRows}</tbody>
</table>
<table>
<caption>Nodes by layer</caption>
<thead><tr><th class="num">Layer</th><th>Node</th><th class="num">Value</th><th class="num">In</th><th class="num">Out</th></tr></thead>
<tbody>${nodeRows}</tbody>
</table>
</body>
</html>
`;
}
